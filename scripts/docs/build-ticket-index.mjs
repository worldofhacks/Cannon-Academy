#!/usr/bin/env node
/**
 * A-035: Deterministic ticket index generator.
 * Reads tickets/T-*.md and tickets/app/A-*.md; writes or checks tickets/INDEX.md.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

const VALID_STATUSES = new Set(['backlog', 'in-progress', 'review-passed', 'done']);
const REQUIRED_FIELDS = ['id', 'title', 'status', 'wave', 'depends_on', 'branch'];
const INDEX_RELATIVE_PATH = 'tickets/INDEX.md';

const ROOT = process.cwd();
const CHECK_MODE = process.argv.includes('--check');

/**
 * @typedef {{
 *   path: string,
 *   id: string,
 *   title: string,
 *   status: string,
 *   wave: string,
 *   dependencies: string[],
 *   branch: string,
 *   track: 'app' | 'engine',
 * }} Ticket
 */

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

function listTicketPaths() {
  const engineDir = join(ROOT, 'tickets');
  const appDir = join(ROOT, 'tickets/app');
  if (!existsSync(engineDir)) fail('tickets/ directory is missing');
  if (!existsSync(appDir)) fail('tickets/app/ directory is missing');

  const engine = readdirSync(engineDir)
    .filter((name) => /^T-.*\.md$/.test(name))
    .map((name) => join(engineDir, name));
  const app = readdirSync(appDir)
    .filter((name) => /^A-.*\.md$/.test(name))
    .map((name) => join(appDir, name));
  return [...engine, ...app].sort();
}

/**
 * @param {string} path
 * @returns {Ticket}
 */
function parseTicket(path) {
  const source = readFileSync(path, 'utf8');
  const relativePath = relative(ROOT, path).split('\\').join('/');
  const missing = [];
  /** @type {Record<string, string>} */
  const fields = {};

  for (const field of REQUIRED_FIELDS) {
    const match = source.match(new RegExp(`^${field}:\\s*(.+)$`, 'm'));
    if (!match) {
      missing.push(field);
      continue;
    }
    fields[field] = match[1].trim();
  }

  if (missing.length > 0) {
    fail(`malformed frontmatter in ${relativePath}: missing required field(s): ${missing.join(', ')}`);
  }

  const dependencies = fields.depends_on
    .replace(/^\[/, '')
    .replace(/\]$/, '')
    .split(',')
    .map((value) => value.trim())
    .filter(Boolean);

  return {
    path: relativePath,
    id: fields.id,
    title: fields.title,
    status: fields.status,
    wave: fields.wave,
    dependencies,
    branch: fields.branch,
    track: relativePath.startsWith('tickets/app/') ? 'app' : 'engine',
  };
}

/**
 * @param {Ticket[]} tickets
 */
function validate(tickets) {
  /** @type {Map<string, string[]>} */
  const byId = new Map();
  for (const ticket of tickets) {
    const list = byId.get(ticket.id) ?? [];
    list.push(ticket.path);
    byId.set(ticket.id, list);
  }

  for (const [id, paths] of byId) {
    if (paths.length > 1) {
      fail(`duplicate id ${id} in ${paths.join(' and ')}`);
    }
  }

  const knownIds = new Set(tickets.map((ticket) => ticket.id));
  for (const ticket of tickets) {
    if (!VALID_STATUSES.has(ticket.status)) {
      fail(`unknown status "${ticket.status}" on ${ticket.id}`);
    }
    for (const dependency of ticket.dependencies) {
      if (!knownIds.has(dependency)) {
        fail(`missing dependency: ${ticket.id} depends on ${dependency}`);
      }
    }
  }
}

/**
 * @param {string} value
 */
function escapeCell(value) {
  return value.replace(/\|/g, '\\|');
}

/**
 * @param {Ticket[]} tickets
 */
function renderIndex(tickets) {
  const sorted = [...tickets].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const lines = [];
  lines.push('# Cannon Academy tickets — canonical index');
  lines.push('');
  lines.push('Generated by `scripts/docs/build-ticket-index.mjs`. Individual ticket frontmatter is');
  lines.push('authoritative for lifecycle and acceptance criteria. Do not hand-edit this file;');
  lines.push('re-run the generator (or `node scripts/docs/build-ticket-index.mjs --check`).');
  lines.push('');
  lines.push('Do not maintain competing live status tables in `TICKETS.md`, `tickets/app/APP-TICKETS.md`,');
  lines.push('README, HANDOFF, or STATE — those documents link here.');
  lines.push('');
  lines.push('## Notes');
  lines.push('');
  lines.push(
    '- **T-023** is intentionally absent by design (never issued; do not invent it from the numeric gap).',
  );
  lines.push('');
  lines.push('## All tickets');
  lines.push('');
  lines.push('| id | track | title | status | wave | dependencies | branch | source |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');

  for (const ticket of sorted) {
    const deps = ticket.dependencies.length === 0 ? 'none' : ticket.dependencies.join(', ');
    const wave = ticket.wave === 'null' ? 'null' : ticket.wave;
    const sourceRelative = relative('tickets', ticket.path).split('\\').join('/');
    const source = `[${ticket.id}](${sourceRelative})`;
    lines.push(
      `| ${escapeCell(ticket.id)} | ${escapeCell(ticket.track)} | ${escapeCell(ticket.title)} | ${escapeCell(ticket.status)} | ${escapeCell(wave)} | ${escapeCell(deps)} | ${escapeCell(ticket.branch)} | ${source} |`,
    );
  }

  lines.push('');
  return `${lines.join('\n')}`;
}

function main() {
  const paths = listTicketPaths();
  const tickets = paths.map(parseTicket);
  validate(tickets);
  const markdown = renderIndex(tickets);
  const indexPath = join(ROOT, INDEX_RELATIVE_PATH);

  if (CHECK_MODE) {
    if (!existsSync(indexPath)) {
      fail('ticket index drift: tickets/INDEX.md is missing');
    }
    const current = readFileSync(indexPath, 'utf8');
    if (current !== markdown) {
      fail('ticket index is stale/out of date (diff vs regenerated output)');
    }
    process.stdout.write('tickets/INDEX.md is current\n');
    return;
  }

  mkdirSync(dirname(indexPath), { recursive: true });
  writeFileSync(indexPath, markdown, 'utf8');
  process.stdout.write(`wrote ${INDEX_RELATIVE_PATH} (${tickets.length} tickets)\n`);
}

main();
